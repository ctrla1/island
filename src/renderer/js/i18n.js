let lang = 'en';

export function setLocale(locale) {
  lang = STRINGS[locale] ? locale : 'en';
  document.documentElement.lang = lang;
}

export const t = (key) => STRINGS[lang][key] ?? key;
export const demoNotifications = () => DEMO_NOTIFICATIONS[lang];
